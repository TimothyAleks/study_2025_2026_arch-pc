#include <stdio.h>

int main() {
    int a = 26;    // Делимое (число, которое делим)
    int b = 5;     // Делитель (число, на которое делим)
    int result;    // Переменная для хранения результата целочисленного деления
    int remainder; // Переменная для хранения остатка от деления

    // Вычисляем результат целочисленного деления (частное)
    result = a / b;

    // Вычисляем остаток от деления
    remainder = a % b;

    // Выводим результаты
    printf("Результат: %d\n", result);
    printf("Остаток от деления: %d\n", remainder);

    return 0;
}
